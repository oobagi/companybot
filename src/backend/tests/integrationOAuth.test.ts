import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { api } from "../convex/_generated/api";
import { ownerAndMember, setMemberSwitch, sideWorkspace, inWorkspace, workspaceOf } from "./helpers";

beforeEach(() => { vi.useFakeTimers(); vi.stubEnv("CONVEX_SITE_URL", "https://companybot.example"); vi.stubEnv("INTEGRATION_APP_URL", "https://app.example/"); });
afterEach(() => { vi.useRealTimers(); vi.unstubAllEnvs(); });
const resource = "https://companybot.example/api/v1";
async function setup() {
	const { t, owner, member } = await ownerAndMember();
	const post = (path: string, body: Record<string, string>) => t.fetch(`/integrations/oauth/${path}`, { method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams(body).toString() });
	const registered = await t.fetch("/integrations/oauth/register", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ client_name: "Example app", redirect_uris: ["https://client.example/callback"], token_endpoint_auth_method: "none" }) });
	expect(registered.status).toBe(201);
	const client = await registered.json();
	const verifier = "a".repeat(64);
	const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(verifier)));
	const challenge = btoa(String.fromCharCode(...digest)).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
	const args = { clientId: client.client_id, redirect: client.redirect_uris[0], resource, challenge, scopes: ["workspace:read", "chats:write"], state: "caller-state" };
	const approve = async () => new URL(await owner.mutation(api.integrationOAuth.approve, { ...args, allow: true, selectedScopes: args.scopes }));
	const exchange = (code: string, overrides = {}) => post("token", { grant_type: "authorization_code", client_id: args.clientId, code, code_verifier: verifier, redirect_uri: args.redirect, resource, ...overrides });
	const call = (access: string, operation = "workspace_get", input = {}) => t.fetch("/api/v1/call", { method: "POST", headers: { Authorization: `Bearer ${access}`, "Content-Type": "application/json" }, body: JSON.stringify({ operation, input }) });
	return { t, owner, member, post, args, verifier, approve, exchange, call };
}
describe("inbound OAuth", () => {
	it("discovers authorization, requires explicit consent, and exchanges PKCE codes for audience-bound access", async () => {
		const { t, owner, args, approve, exchange, call } = await setup();
		const denied = await t.fetch("/api/v1/tools");
		expect(denied.headers.get("WWW-Authenticate")).toContain("/.well-known/oauth-protected-resource/api/v1");
		expect((await (await t.fetch("/.well-known/oauth-protected-resource/mcp")).json()).authorization_servers).toEqual(["https://companybot.example"]);
		const metadata = await (await t.fetch("/.well-known/oauth-authorization-server")).json();
		expect(metadata.code_challenge_methods_supported).toEqual(["S256"]);
		const authorize = { response_type: "code", client_id: args.clientId, redirect_uri: args.redirect, resource, code_challenge: args.challenge, code_challenge_method: "S256", scope: args.scopes.join(" "), state: args.state };
		const started = await t.fetch(`/integrations/oauth/authorize?${new URLSearchParams(authorize)}`);
		expect(started.status).toBe(302);
		expect(new URL(started.headers.get("Location")!).origin).toBe("https://app.example");
		expect((await t.fetch(`/integrations/oauth/authorize?${new URLSearchParams({ ...authorize, redirect_uri: "https://evil.example/" })}`)).status).toBe(400);
		expect((await t.fetch(`/integrations/oauth/authorize?${new URLSearchParams({ ...authorize, code_challenge_method: "plain" })}`)).status).toBe(400);
		const no = new URL(await owner.mutation(api.integrationOAuth.approve, { ...args, allow: false, selectedScopes: [] }));
		expect(no.searchParams.get("error")).toBe("access_denied");
		expect((await owner.query(api.integrationTokens.list)).tokens).toHaveLength(0);
		const redirect = await approve();
		expect(redirect.searchParams.get("state")).toBe(args.state);
		expect(redirect.searchParams.get("iss")).toBe("https://companybot.example");
		const code = redirect.searchParams.get("code")!;
		expect((await exchange(code, { code_verifier: "z".repeat(64) })).status).toBe(400);
		expect((await exchange(code, { resource: "https://evil.example/api" })).status).toBe(400);
		const tokens = await (await exchange(code)).json();
		expect(tokens.token_type).toBe("Bearer");
		expect((await call(tokens.access_token)).status).toBe(200);
		const mcp = await t.fetch("/mcp", { method: "POST", headers: { Authorization: `Bearer ${tokens.access_token}`, "Content-Type": "application/json", Accept: "application/json, text/event-stream" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }) });
		expect(mcp.status).toBe(401);
		const stored = JSON.stringify(await t.run(async ctx => ({ tokens: await ctx.db.query("integrationTokens").collect(), codes: await ctx.db.query("integrationOAuthCodes").collect(), refresh: await ctx.db.query("integrationRefreshTokens").collect() })));
		for (const secret of [code, tokens.access_token, tokens.refresh_token]) expect(stored).not.toContain(secret);
		expect((await exchange(code)).status).toBe(400);
		expect((await call(tokens.access_token)).status).toBe(401);
	});
	it("rotates refresh tokens, rejects widening, and revokes the family on reuse or explicit revocation", async () => {
		const { args, post, approve, exchange, call } = await setup();
		let tokens = await (await exchange((await approve()).searchParams.get("code")!)).json();
		const refresh = (value: string, overrides = {}) => post("token", { grant_type: "refresh_token", client_id: args.clientId, refresh_token: value, resource, ...overrides });
		vi.advanceTimersByTime(61000);
		expect((await refresh(tokens.refresh_token, { scope: "records:write" })).status).toBe(400);
		const next = await (await refresh(tokens.refresh_token, { scope: "workspace:read" })).json();
		expect(next.scope).toBe("workspace:read");
		expect((await call(tokens.access_token)).status).toBe(401);
		expect((await call(next.access_token)).status).toBe(200);
		expect((await refresh(tokens.refresh_token)).status).toBe(400);
		expect((await call(next.access_token)).status).toBe(401);
		tokens = await (await exchange((await approve()).searchParams.get("code")!)).json();
		expect((await post("revoke", { client_id: args.clientId, token: tokens.refresh_token })).status).toBe(200);
		expect((await call(tokens.access_token)).status).toBe(401);
		expect((await post("revoke", { client_id: args.clientId, token: "unknown" })).status).toBe(200);
		expect((await post("revoke", { client_id: "unknown", token: "unknown" })).status).toBe(200);
	});
	it("requires current role and membership at consent, exchange and refresh, and keeps workspace selection explicit", async () => {
		const { t, owner, member, args, post, exchange, call } = await setup();
		await expect(member.mutation(api.integrationOAuth.approve, { ...args, allow: true, selectedScopes: args.scopes })).rejects.toThrow();
		await setMemberSwitch(owner, "integrations.manage", true);
		const approved = new URL(await member.mutation(api.integrationOAuth.approve, { ...args, allow: true, selectedScopes: args.scopes }));
		await setMemberSwitch(owner, "integrations.manage", false);
		expect((await exchange(approved.searchParams.get("code")!)).status).toBe(400);
		await setMemberSwitch(owner, "integrations.manage", true);
		const tokens = await (await exchange(approved.searchParams.get("code")!)).json();
		const other = await sideWorkspace(t, "owner@co.com");
		const chatId = await inWorkspace(owner, other.workspaceId).mutation(api.chats.createChannel, { name: "other", private: false });
		expect((await call(tokens.access_token, "messages_post", { chatId, text: "No", requestKey: "cross-workspace-0001" })).status).toBe(403);
		const workspaceId = await workspaceOf(member);
		await t.run(async ctx => { const row = (await ctx.db.query("members").withIndex("by_user", q => q.eq("userId", member.userId).eq("workspaceId", workspaceId)).first())!; const { _id, _creationTime: _time, ...copy } = row; await ctx.db.delete(_id); await ctx.db.insert("members", copy); });
		vi.advanceTimersByTime(61000);
		expect((await post("token", { grant_type: "refresh_token", client_id: args.clientId, refresh_token: tokens.refresh_token, resource })).status).toBe(400);
		expect((await call(tokens.access_token)).status).toBe(401);
	});
});
